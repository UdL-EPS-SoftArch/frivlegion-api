-- Initial database schema for FrivLegion

CREATE TABLE player (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(255) NOT NULL UNIQUE,
    email VARCHAR(255) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    created_at TIMESTAMP,
    account_non_expired BOOLEAN NOT NULL,
    account_non_locked BOOLEAN NOT NULL,
    credentials_non_expired BOOLEAN NOT NULL,
    enabled BOOLEAN NOT NULL,
    version BIGINT
);

CREATE TABLE game (
    id VARCHAR(255) NOT NULL PRIMARY KEY,
    title VARCHAR(255) NOT NULL,
    description TEXT,
    thumbnail_url VARCHAR(255),
    category VARCHAR(255),
    is_active BOOLEAN NOT NULL,
    version BIGINT
);

CREATE TABLE record (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    description VARCHAR(500),
    status VARCHAR(255),
    created TIMESTAMP,
    modified TIMESTAMP,
    owned_by_id BIGINT,
    version BIGINT,
    CONSTRAINT fk_record_owned_by FOREIGN KEY (owned_by_id) REFERENCES player (id)
);

CREATE TABLE score (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    player_id BIGINT NOT NULL,
    game_id VARCHAR(255) NOT NULL,
    score_value INT NOT NULL,
    achieved_at TIMESTAMP,
    version BIGINT,
    CONSTRAINT fk_score_player FOREIGN KEY (player_id) REFERENCES player (id),
    CONSTRAINT fk_score_game FOREIGN KEY (game_id) REFERENCES game (id)
);

CREATE TABLE game_state (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    player_id BIGINT NOT NULL,
    game_id VARCHAR(255) NOT NULL,
    payload TEXT,
    updated_at TIMESTAMP,
    version BIGINT,
    CONSTRAINT fk_game_state_player FOREIGN KEY (player_id) REFERENCES player (id),
    CONSTRAINT fk_game_state_game FOREIGN KEY (game_id) REFERENCES game (id)
);
